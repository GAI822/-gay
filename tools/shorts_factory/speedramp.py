"""AI生成クリップを「x1 → x2 → x3」の段階型ショートに仕上げる。

分析(analysis/shorts_627)で伸びた「段階型」を、短いAIクリップに当てはめて尺を伸ばす。
BGMは段階ごとにテンポが上がる自作曲（dance.py の音源を流用）。

使い方: python3 tools/shorts_factory/speedramp.py clip.mp4 --id realcat_001 --out out/ --synthetic
"""
import argparse
import json
import subprocess
import wave
from pathlib import Path

import dance

FONT = dance.FONT
TITLE = {"en": "Cat dance, but it gets faster \U0001F431", "ja": "だんだん速くなるネコダンス\U0001F431",
         "zh": "越来越快的猫咪舞\U0001F431", "es": "Baile de gato, cada vez más rápido \U0001F431"}
DESC = {"en": "Which speed was best: x1, x2 or x3? (AI-generated video)",
        "ja": "x1・x2・x3、どのスピードが好き？（AI生成の映像です）",
        "zh": "x1、x2、x3，你最喜欢哪个速度？（AI生成视频）",
        "es": "¿Qué velocidad fue mejor: x1, x2 o x3? (video generado con IA)"}


def duration(p):
    return float(subprocess.check_output(["ffprobe", "-v", "quiet", "-show_entries", "format=duration",
                                          "-of", "csv=p=0", str(p)]).decode())


def build(clip, vid, outdir, synthetic, speeds=(1, 2, 3)):
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    d = duration(clip)
    parts, lens = [], []
    for i, s in enumerate(speeds):
        seg = outdir / f"_{vid}_{i}.mp4"
        label = f"x{s}"
        # 速度を上げ、段階表示を入れ、1080x1920に整える
        vf = (f"setpts=PTS/{s},scale=1080:1920:force_original_aspect_ratio=increase:flags=lanczos,crop=1080:1920,fps=30,"
              f"drawtext=fontfile={FONT}:text='{label}':fontsize=130:fontcolor=white:borderw=9:bordercolor=black@0.6:"
              f"x=(w-text_w)/2:y=70")
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(clip), "-an", "-vf", vf,
                        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", str(seg)], check=True)
        parts.append(seg)
        lens.append(d / s)
    lst = outdir / f"_{vid}_list.txt"
    lst.write_text("".join(f"file '{p.resolve()}'\n" for p in parts))
    silent = outdir / f"_{vid}_v.mp4"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(lst),
                    "-c", "copy", str(silent)], check=True)
    total = sum(lens)
    # BGM: dance.Show の拍表を各段階の長さに合わせて作り直す
    show = dance.Show(hash(vid) % 10**6)
    show.beats, show.stage_start = [], []
    for i, (L, bpm) in enumerate(zip(lens, show.bpms)):
        start, beat = sum(lens[:i]), 60 / bpm
        show.stage_start.append(start)
        show.beats += [(start + k * beat, beat) for k in range(int(L / beat))]
    show.end_dance, show.total = total - 0.05, total + 0.3
    wav = outdir / f"_{vid}.wav"
    with wave.open(str(wav), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(dance.SR)
        w.writeframes(show.music(7).tobytes())
    mp4 = outdir / f"{vid}.mp4"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(silent), "-i", str(wav), "-map", "0:v", "-map", "1:a",
                    "-c:v", "copy", "-c:a", "aac", "-b:a", "160k", "-shortest", str(mp4)], check=True)
    for p in [*parts, lst, silent, wav]:
        p.unlink()

    def ts(x):
        return f"00:00:{int(x):02d},{int((x % 1) * 1000):03d}"
    starts = [sum(lens[:i]) for i in range(len(lens))] + [total]
    for lang in dance.SUBS:
        subs = dance.SUBS[lang]
        (outdir / f"{vid}.{lang}.srt").write_text("\n".join(
            f"{k + 1}\n{ts(starts[k])} --> {ts(starts[k + 1])}\n{subs[k]}\n" for k in range(3)), encoding="utf-8")
    meta = {"id": vid, "format": "speedramp", "source_clip": str(clip), "speeds": list(speeds),
            "duration_s": round(total, 1), "ai_generated": True, "synthetic_disclosure": synthetic,
            "assets": "video generated by AI (Higgsfield) from an original prompt; music generated by dance.py (original)",
            "title": {k: f"{v} #shorts" for k, v in TITLE.items()}, "description": DESC,
            "hashtags": ["#shorts", "#cat", "#dance"]}
    (outdir / f"{vid}.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    return mp4


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("clip")
    ap.add_argument("--id", required=True)
    ap.add_argument("--out", default="out")
    ap.add_argument("--synthetic", action="store_true", help="リアルなAI映像（YouTubeの合成コンテンツ申告をオン）")
    a = ap.parse_args()
    print(build(a.clip, a.id, a.out, a.synthetic))

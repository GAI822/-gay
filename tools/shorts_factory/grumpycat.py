"""「立ち上がった瞬間に不機嫌顔」→ 二足歩行ダンス x1/x2/x3 のミーム風ショートを組み立てる。

入力:
  standup.mp4 : 四つ足から立ち上がるAIクリップ（立ち上がり時刻 --drop）
  dance.mp4   : 同じ猫の二足歩行クリップ（使う区間 --dance-from/--dance-to）
使い方:
  python3 tools/shorts_factory/grumpycat.py standup.mp4 dance.mp4 --id grumpycat_001 --out out/ \
      --drop 0.95 --face-at 2.6 --dance-from 0.5 --dance-to 5.5
"""
import argparse
import json
import subprocess
import wave
from pathlib import Path

import dance
import memebeat

FIT = "scale=1080:1920:force_original_aspect_ratio=increase:flags=lanczos,crop=1080:1920,fps=30"
LABEL = ("drawtext=fontfile={f}:text='{t}':fontsize=130:fontcolor=white:borderw=9:bordercolor=black@0.6:"
         "x=(w-text_w)/2:y=70")
TITLE = {"en": "When the cat stands up \U0001F610 #shorts", "ja": "立ち上がった瞬間の顔\U0001F610 #shorts",
         "zh": "猫站起来那一刻的表情\U0001F610 #shorts", "es": "Cuando el gato se levanta \U0001F610 #shorts"}
DESC = {"en": "Rate his mood 1-10 \U0001F610 (AI-generated video)",
        "ja": "この顔、不機嫌度は10点満点で何点？（AI生成の映像です）",
        "zh": "这表情的不爽程度打几分？1-10（AI生成视频）",
        "es": "Califica su mal humor del 1 al 10 (video generado con IA)"}
SUBS = {"en": ("...", "Not amused.", "Faster!", "Which speed was best? x1 / x2 / x3"),
        "ja": ("…", "は？", "もっと速く！", "どのスピードが好き？ x1 / x2 / x3"),
        "zh": ("……", "哈？", "更快！", "你喜欢哪个速度？x1 / x2 / x3"),
        "es": ("...", "¿Perdón?", "¡Más rápido!", "¿Cuál velocidad fue mejor? x1 / x2 / x3")}


def ff(*args):
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *args], check=True)


def enc(src, dst, vf, extra=()):
    ff(*extra, "-i", str(src), "-an", "-vf", vf, "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", str(dst))


def build(standup, dance_clip, vid, outdir, drop, face_at, d0, d1):
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    tmp = [out / f"_{vid}_{k}.mp4" for k in range(6)]
    f = dance.FONT
    # 1) 立ち上がり全体  2) 不機嫌顔のアップ（0.8秒、軽く寄る）
    enc(standup, tmp[0], FIT)
    enc(standup, tmp[1], "crop=iw*0.55:ih*0.32:iw*0.24:ih*0.13,scale=1080:1920:force_original_aspect_ratio=increase,"
                         "crop=1080:1920,fps=30", ("-ss", str(face_at), "-t", "0.8"))
    # 3) 二足歩行区間を往復させて x1 → 4) x2 → 5) x3
    span = d1 - d0
    pingpong = f"[0:v]trim={d0}:{d1},setpts=PTS-STARTPTS,split[a][b];[b]reverse[r];[a][r]concat=n=2:v=1[p]"
    for k, s in zip((2, 3, 4), (1, 2, 3)):
        ff("-i", str(dance_clip), "-filter_complex",
           f"{pingpong};[p]setpts=PTS/{s},{FIT},{LABEL.format(f=f, t=f'x{s}')}[v]", "-map", "[v]", "-an",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", str(tmp[k]))
    parts = [tmp[0], tmp[1], tmp[2], tmp[3], tmp[4]]
    lens = [float(subprocess.check_output(["ffprobe", "-v", "quiet", "-show_entries", "format=duration", "-of",
                                           "csv=p=0", str(p)])) for p in parts]
    lst = out / f"_{vid}_list.txt"
    lst.write_text("".join(f"file '{p.resolve()}'\n" for p in parts))
    ff("-f", "concat", "-safe", "0", "-i", str(lst), "-c", "copy", str(tmp[5]))
    total = sum(lens)
    st = [sum(lens[:i]) for i in range(len(lens))] + [total]
    # 音楽: 立ち上がりでドロップ、x2/x3でテンポアップ
    sections = [(0, 150), (st[3], 175), (st[4], 200)]
    wav = out / f"_{vid}.wav"
    with wave.open(str(wav), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(memebeat.SR)
        w.writeframes(memebeat.render(total, drop, sections, seed=4353).tobytes())
    mp4 = out / f"{vid}.mp4"
    ff("-i", str(tmp[5]), "-i", str(wav), "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac",
       "-b:a", "160k", "-shortest", str(mp4))
    for p in [*tmp, lst, wav]:
        p.unlink()

    def ts(x):
        return f"00:00:{int(x):02d},{int((x % 1) * 1000):03d}"
    cues = [(0, drop), (drop, st[2]), (st[3], st[4]), (st[4], total)]
    for lang, lines in SUBS.items():
        (out / f"{vid}.{lang}.srt").write_text("\n".join(
            f"{k + 1}\n{ts(a)} --> {ts(b)}\n{txt}\n" for k, ((a, b), txt) in enumerate(zip(cues, lines))),
            encoding="utf-8")
    meta = {"id": vid, "format": "grumpycat", "duration_s": round(total, 1), "drop_at": drop,
            "ai_generated": True, "synthetic_disclosure": True,
            "assets": "video generated by AI (Higgsfield/Seedance 1.5) from original prompts; "
                      "music generated by memebeat.py (original)",
            "title": TITLE, "description": DESC, "hashtags": ["#shorts", "#cat", "#funnycat"]}
    (out / f"{vid}.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    return mp4


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("standup")
    ap.add_argument("dance_clip")
    ap.add_argument("--id", required=True)
    ap.add_argument("--out", default="out")
    ap.add_argument("--drop", type=float, default=0.95)
    ap.add_argument("--face-at", type=float, default=2.6)
    ap.add_argument("--dance-from", type=float, default=0.5)
    ap.add_argument("--dance-to", type=float, default=5.5)
    a = ap.parse_args()
    print(build(a.standup, a.dance_clip, a.id, a.out, a.drop, a.face_at, a.dance_from, a.dance_to))
